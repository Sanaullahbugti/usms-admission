type PackOptions = {
  slug: string;
  name: string;
  cnic: string;
  district: string;
  hsc: string;
  total?: string;
  photo?: "png" | "svg" | "missing";
  includeChallan?: boolean;
  statuses?: Partial<Record<"cnic" | "ssc" | "hsc" | "domicile" | "photo" | "challan", DocumentStatus>>;
};

function doc(
  id: string,
  title: string,
  fileName: string,
  sizeLabel: string,
  status: DocumentStatus,
  url: string | undefined,
  kind: ApplicationDocument["kind"],
  summary?: string,
): ApplicationDocument {
  return { id, title, fileName, sizeLabel, status, url, kind, summary };
}

function pack(options: PackOptions): ApplicationDocument[] {
  const base = `/mock-docs/${options.slug}`;
  const total = options.total ?? "1100";
  const statuses = options.statuses ?? {};
  const photoKind = options.photo ?? "png";
  const docs: ApplicationDocument[] = [
    doc(
      `${options.slug}-cnic`,
      "CNIC / B-Form",
      `CNIC_${options.name.replaceAll(" ", "_")}.pdf`,
      "1.1 MB",
      statuses.cnic ?? "UPLOADED",
      `${base}/cnic.pdf`,
      "pdf",
      `CNIC ${options.cnic}`,
    ),
    doc(
      `${options.slug}-ssc`,
      "SSC / Matric certificate",
      `SSC_${options.name.replaceAll(" ", "_")}.pdf`,
      "1.6 MB",
      statuses.ssc ?? "UPLOADED",
      `${base}/ssc.pdf`,
      "pdf",
      `SSC record · ${options.district}`,
    ),
    doc(
      `${options.slug}-hsc`,
      "HSC / Intermediate marksheet",
      `HSC_${options.name.replaceAll(" ", "_")}.pdf`,
      "2.1 MB",
      statuses.hsc ?? "UPLOADED",
      `${base}/hsc.pdf`,
      "pdf",
      `${options.hsc} / ${total} · ${options.district}`,
    ),
    doc(
      `${options.slug}-dom`,
      "Domicile certificate",
      `Domicile_${options.district}.pdf`,
      "940 KB",
      statuses.domicile ?? "UPLOADED",
      `${base}/domicile.pdf`,
      "pdf",
      options.district,
    ),
  ];
  if (photoKind === "missing") {
    docs.push(doc(`${options.slug}-photo`, "Passport photograph", "", "", "MISSING", undefined, "image"));
  } else if (photoKind === "svg") {
    docs.push(
      doc(
        `${options.slug}-photo`,
        "Passport photograph",
        `${options.name.replaceAll(" ", "_")}_photo.svg`,
        "12 KB",
        statuses.photo ?? "UPLOADED",
        `${base}/photo.svg`,
        "svg",
        "Vector passport photo sample",
      ),
    );
  } else {
    docs.push(
      doc(
        `${options.slug}-photo`,
        "Passport photograph",
        `${options.name.replaceAll(" ", "_")}_photo.png`,
        "220 KB",
        statuses.photo ?? "UPLOADED",
        `${base}/photo.png`,
        "image",
        "Passport photo sample",
      ),
    );
  }
  if (options.includeChallan) {
    docs.push(
      doc(
        `${options.slug}-challan`,
        "Paid bank challan",
        `Challan_${options.name.replaceAll(" ", "_")}.pdf`,
        "480 KB",
        statuses.challan ?? "UPLOADED",
        `${base}/challan.pdf`,
        "pdf",
        "PKR 3,000 fee slip",
      ),
    );
  }
  return docs;
}

function review(
  id: string,
  action: ReviewAction,
  message: string,
  createdAt: string,
  items?: ApplicationFile["reviews"][number]["items"],
): ApplicationFile["reviews"][number] {
  return { id, action, message, createdAt, reviewerLabel: "Admissions Officer", items };
}

